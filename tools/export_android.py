"""Export what the Android port needs from the Python reference.

    .venv/bin/python tools/export_android.py              # logo template + small test frames
    .venv/bin/python tools/export_android.py DIR COUNT    # also a large fixture set into DIR
"""
import os
import sys

import cv2

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import bench  # noqa: E402
from astracode import decode  # noqa: E402

APP = os.path.join(ROOT, "android/app/src")


def write_template():
    def arr(name, values):
        body = ",\n        ".join(", ".join("%.4ff" % v for v in values[i:i + 10]) for i in range(0, len(values), 10))
        return f"    val {name} = floatArrayOf(\n        {body},\n    )\n"
    path = os.path.join(APP, "main/java/app/astracode/scanner/decode/LogoTemplate.kt")
    with open(path, "w") as f:
        f.write("// Generated by tools/export_android.py from the logo artwork. Do not edit.\n")
        f.write("package app.astracode.scanner.decode\n\n")
        f.write("/** Sample points over the logo area (model units) and the expected ink coverage at each. */\n")
        f.write("internal object LogoTemplate {\n")
        f.write(arr("X", decode._LOGO_XY[:, 0]))
        f.write(arr("Y", decode._LOGO_XY[:, 1]))
        f.write(arr("INK", decode._LOGO_T))
        f.write("}\n")


def write_frames(out, seeds, level=1.0, negatives=0, quality=95):
    os.makedirs(out, exist_ok=True)
    rows = []
    for seed in seeds:
        img, meta = bench.make_case(seed, level)
        name = f"frame_{seed:05d}.jpg"
        cv2.imwrite(os.path.join(out, name), img, [cv2.IMWRITE_JPEG_QUALITY, quality])
        # What the reference scanner reads from the file as saved.
        got = decode.scan(cv2.imread(os.path.join(out, name)))
        rows.append(f"{name},{meta['number']:012d},{got[0]['text'] if got else ''}")
    for i in range(negatives):
        name = f"empty_{i:05d}.jpg"
        cv2.imwrite(os.path.join(out, name), bench.make_negative(10 ** 6 + i), [cv2.IMWRITE_JPEG_QUALITY, quality])
        rows.append(f"{name},,")
    with open(os.path.join(out, "expected.csv"), "w") as f:
        f.write("file,number,reference\n" + "\n".join(rows) + "\n")


if __name__ == "__main__":
    write_template()
    write_frames(os.path.join(APP, "test/resources/frames"), range(8), negatives=2, quality=80)
    if len(sys.argv) > 2:
        write_frames(sys.argv[1], range(100, 100 + int(sys.argv[2])), negatives=int(sys.argv[2]) // 4)
